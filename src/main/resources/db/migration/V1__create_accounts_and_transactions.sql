create table accounts (
    id             bigint generated by default as identity primary key,
    owner_name     varchar(50)                 not null,
    account_number varchar(20)                 not null unique,
    balance        numeric(20, 2)              not null,
    currency       varchar(3)                  not null,
    status         varchar(16)                 not null,
    created_at     timestamp(6) with time zone not null,

    constraint check_account_balance_is_not_negative check (balance >= 0),
    constraint check_account_currency_is_known check (currency in ('GEL', 'USD', 'EUR')),
    constraint check_account_status_is_known check (status in ('ACTIVE', 'CLOSED'))
);

create table transactions (
    id              bigint generated by default as identity primary key,
    from_account_id bigint                      not null references accounts (id),
    to_account_id   bigint                      not null references accounts (id),
    amount          numeric(20, 2)              not null,
    status          varchar(16)                 not null,
    failure_reason  varchar(30),
    idempotency_key varchar(128)                not null unique,
    created_at      timestamp(6) with time zone not null,

    constraint check_transaction_amount_is_positive check (amount > 0),
    constraint check_transaction_accounts_are_different check (from_account_id <> to_account_id),
    constraint check_transaction_status_is_known check (status in ('SUCCESS', 'FAILED')),
    constraint check_transaction_failure_reason_is_known
        check (failure_reason in ('INSUFFICIENT_FUNDS', 'CURRENCY_MISMATCH', 'ACCOUNT_CLOSED')),
    constraint check_transaction_failure_reason_matches_status
        check ((status = 'SUCCESS' and failure_reason is null)
            or (status = 'FAILED' and failure_reason is not null))
);

-- Account history reads incoming and outgoing transfers separately, newest first.
create index transactions_from_account_id_created_at_idx on transactions (from_account_id, created_at);
create index transactions_to_account_id_created_at_idx on transactions (to_account_id, created_at);
